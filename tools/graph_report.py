"""python -m tools.graph_report [--out-dir artifacts]

Captures the model twice, with torch.fx.symbolic_trace (module-level graph) and torch.export (ATen-level graph),
checks both reproduce the eager logits, and writes artifacts/graph_report.{json,md} with an explanation.
"""
import json
import math
from collections import Counter
from pathlib import Path

import torch
from torch.fx import Node, symbolic_trace
from torch.fx.passes.shape_prop import ShapeProp

from gpt2_pytorch.data import FIXED_INPUT_IDS
from gpt2_pytorch.utils.cli import common_parser, load_model

parser = common_parser(__doc__)
parser.add_argument("--out-dir", default="artifacts")
args = parser.parse_args()

model, config, _ = load_model(args)
x = FIXED_INPUT_IDS.to(next(model.parameters()).device)


def tname(t):
    return t if isinstance(t, str) else getattr(t, "__name__", str(t))


def shape_of(n: Node):
    v = n.meta.get("val", n.meta.get("tensor_meta"))
    return list(v.shape) if hasattr(v, "shape") else None


# ---- torch.fx.symbolic_trace ------------------------------------------------------------------------------------
gm = symbolic_trace(model, concrete_args={"labels": None, "position_ids": None, "return_debug": False})
ShapeProp(gm).propagate(x)
mods = dict(gm.named_modules())
fx_ops = Counter(n.op for n in gm.graph.nodes)
fx_modules = Counter(type(mods[n.target]).__name__ for n in gm.graph.nodes if n.op == "call_module")
fx_funcs = Counter(tname(n.target) for n in gm.graph.nodes if n.op in ("call_function", "call_method"))

# ---- torch.export -----------------------------------------------------------------------------------------------
with torch.no_grad():
    ep = torch.export.export(model, (x,))
    eager = model(x)
    fx_ok = torch.equal(gm(x), eager)
    ex_err = (ep.module()(x) - eager).abs().max().item()

sig = Counter(s.kind.name for s in ep.graph_signature.input_specs)
aten = Counter(str(n.target) for n in ep.graph.nodes if n.op == "call_function")
placeholders = {n.name: n for n in ep.graph.nodes if n.op == "placeholder"}
# tied weights appear as two placeholders over one storage, so count unique storages
param_elems = sum({t.data_ptr(): t.numel() for k, t in ep.state_dict.items() if k in dict(model.named_parameters())}.values())
# a parameter read by two different kinds of op is a tied weight
tied = [
    {"param": n.name, "used_by": sorted({str(u.target) for u in n.users})}
    for n in placeholders.values()
    if n.name.startswith("p_") and len({str(u.target) for u in n.users}) > 1
]
# 2*M*N*K style FLOPs: 2 * output elements * contracted dim (first operand's last dim)
matmuls = []
for n in ep.graph.nodes:
    if n.op == "call_function" and str(n.target) in ("aten.linear.default", "aten.matmul.default", "aten.bmm.default"):
        out, a = shape_of(n), shape_of(n.args[0])
        matmuls.append({"name": n.name, "op": str(n.target), "in": a, "out": out, "flops": 2 * math.prod(out) * a[-1]})
flops = sum(m["flops"] for m in matmuls)

report = {
    "model": {"layers": config.num_layers, "hidden": config.hidden_size, "heads": config.num_heads, "input_shape": list(x.shape)},
    "equivalence": {"fx_equals_eager_bitwise": fx_ok, "export_max_abs_diff_vs_eager": ex_err},
    "fx": {"nodes": len(gm.graph.nodes), "by_opcode": dict(fx_ops), "leaf_modules": dict(fx_modules), "top_functions": dict(fx_funcs.most_common(10))},
    "export": {
        "nodes": len(ep.graph.nodes),
        "inputs_by_kind": dict(sig),
        "parameter_elements": param_elems,
        "tied_parameters": tied,
        "aten_ops": dict(aten.most_common()),
        "matmul_flops": flops,
        "matmuls": matmuls,
    },
}
out = Path(args.out_dir)
out.mkdir(parents=True, exist_ok=True)
(out / "graph_report.json").write_text(json.dumps(report, indent=1))


def table(rows, head):
    return ["| " + " | ".join(head) + " |", "|" + "---|" * len(head), *("| " + " | ".join(map(str, r)) + " |" for r in rows)]


L = config.num_layers
md = [
    "# FX + torch.export graph report",
    "",
    f"Input `{list(x.shape)}` int64 token ids; {L} blocks, hidden {config.hidden_size}, {config.num_heads} heads. Generated by `python -m tools.graph_report`; machine-readable twin: `graph_report.json`.",
    "",
    "## What this shows",
    "",
    "The same model is captured as a graph twice. Both graphs are static: no Python control flow remains, only operations on tensors.",
    "",
    "- **`torch.fx.symbolic_trace`** runs the model on proxy objects and records each call. Layers like `Linear`/`LayerNorm`/`Embedding` stay as single `call_module` nodes; arithmetic written inline (attention maths, GELU) becomes `call_function`/`call_method` nodes. Good for seeing the model's *structure*.",
    "- **`torch.export`** (`ExportedProgram`) lowers everything to ATen ops and lifts weights and buffers out as explicit graph inputs, so the graph is self-contained and its inputs say exactly which tensors the model owns. Good for seeing the model's *computation*.",
    "",
    "## Correctness",
    "",
    f"- FX module output equals eager logits bit-for-bit: **{fx_ok}**",
    f"- Exported module max |diff| vs eager logits: **{ex_err:.2e}**",
    "",
    "## FX graph",
    "",
    f"{len(gm.graph.nodes)} nodes. Opcodes: " + ", ".join(f"`{k}` {v}" for k, v in fx_ops.items()) + ".",
    "",
    "`call_module` leaves (the layers FX does not look inside):",
    "",
    *table(fx_modules.most_common(), ["module type", "count"]),
    "",
    "Most frequent inlined operations (attention scaling, causal masking, residual adds, head reshapes):",
    "",
    *table(fx_funcs.most_common(10), ["function / method", "count"]),
    "",
    "## torch.export graph",
    "",
    f"{len(ep.graph.nodes)} nodes. Graph inputs by kind: " + ", ".join(f"`{k}` {v}" for k, v in sig.items()) + f". Parameters hold {param_elems:,} unique elements (tied weights counted once).",
    "",
    "- `PARAMETER` inputs are the trainable weights; `BUFFER` inputs are non-trainable tensors (position ids and the per-block causal masks); `USER_INPUT` is `input_ids`.",
    "",
    "Tied weights (one parameter read by different ops):",
    "",
    *(f"- `{t['param']}` is read by {', '.join(f'`{u}`' for u in t['used_by'])}: the token embedding and the `lm_head` share one matrix." for t in tied),
    *([] if tied else ["- none detected"]),
    "",
    "ATen op histogram:",
    "",
    *table(list(aten.most_common()), ["aten op", "count"]),
    "",
    f"Matrix multiplies: {len(matmuls)} ops, **{flops / 1e6:,.1f} MFLOPs** for this input (2 x output elements x contracted dim; elementwise ops ignored). Full per-op list in the JSON.",
    "",
    *table([(m["name"], m["op"].removeprefix("aten.").removesuffix(".default"), m["in"], m["out"], f"{m['flops'] / 1e6:,.1f}") for m in matmuls[:12]], ["node", "op", "input", "output", "MFLOPs"]),
    "",
    f"(first 12 of {len(matmuls)} shown; the {L} blocks repeat the same pattern: QKV projection, QK^T, attention x V, output projection, MLP up, MLP down, plus the final `lm_head`.)",
    "",
    "## Reading the two graphs together",
    "",
    "FX tells you *which layers run in which order*; export tells you *which tensors and ATen kernels they become*. Per block the FX graph is the same node pattern repeated, and the export graph is that pattern with weights as inputs. The two agree numerically with eager PyTorch, so either graph is a faithful, frozen description of the model for this input shape (export specialises on batch/sequence length; FX records the shapes it saw).",
    "",
]
(out / "graph_report.md").write_text("\n".join(md))
print(f"fx {len(gm.graph.nodes)} nodes (== eager: {fx_ok}), export {len(ep.graph.nodes)} nodes (max diff {ex_err:.1e}), {flops / 1e6:,.1f} MFLOPs")
print(f"wrote {out / 'graph_report.md'}, {out / 'graph_report.json'}")
