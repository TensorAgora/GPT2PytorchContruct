"""python -m tools.export_formats.run_all [--model distilgpt2|tiny|all] [--only onnx,gguf,...]

Exports the model to every format Tensormorph must inspect, each exporter in its own process (TensorFlow, Core ML and
OpenVINO never share an interpreter), logs in exports/<model>/logs/. Every written file is loaded back with its own
runtime and its logits compared with PyTorch. Writes exports/<model>/manifest.json and an index README.md.

Run with the export environment:  .venv-export/bin/python -m tools.export_formats.run_all --model all
"""
import argparse
import json
import platform
import subprocess
import sys
import time
from importlib.metadata import PackageNotFoundError, version
from pathlib import Path

from .common import MODELS

# order matters: tensorrt builds from the ONNX file
EXPORTERS = ["pytorch_formats", "onnx_format", "gguf_format", "tensorflow_formats", "coreml_format", "openvino_format", "tensorrt_format"]
PACKAGES = ["torch", "onnx", "onnxscript", "onnxruntime", "gguf", "tensorflow", "keras", "coremltools", "openvino", "safetensors", "numpy"]


def versions() -> dict:
    found = {}
    for p in PACKAGES:
        try:
            found[p] = version(p)
        except PackageNotFoundError:
            found[p] = None
    return found


def size(n: int) -> str:
    for unit in ("B", "KiB", "MiB", "GiB"):
        if n < 1024 or unit == "GiB":
            return f"{n:.0f} {unit}" if unit == "B" else f"{n:.1f} {unit}"
        n /= 1024


def readme(model: str, entries: list, env: dict) -> str:
    ok = sum(e["status"] == "ok" for e in entries)
    lines = [
        f"# {model}: export fixtures", "",
        f"{len(entries)} variants: {ok} ok, " + ", ".join(f"{sum(e['status'] == s for e in entries)} {s}" for s in ("mismatch", "failed", "skipped")) + ".",
        "Generated by `python -m tools.export_formats.run_all`; machine-readable twin: `manifest.json` (sha256 per file).", "",
        "Every file was loaded back with its own runtime (PyTorch, onnxruntime, gguf-py, Keras/TF, TFLite, Core ML, OpenVINO) and its",
        "logits on the fixed [2, 8] ids compared with the PyTorch model. `max rel diff` is relative to max |logit|; `ok` means within the",
        "variant's tolerance (1e-4 for float32, looser for fp16 / int8 / 4-bit). `graph` says what the file holds besides weights.", "",
        "| format | variant | files | size | graph | status | max rel diff | notes |", "|---|---|---|---:|---|---|---:|---|",
    ]
    for e in entries:
        files = "<br>".join(f"`{Path(f['path']).relative_to(f'exports/{model}')}`" for f in e["files"]) or "—"
        total = size(sum(f["size"] for f in e["files"])) if e["files"] else "—"
        rel = f"{e['verify']['max_rel_diff']:.1e}" if e.get("verify") else "—"
        note = e.get("notes", "") + (f" **{e['error']}**" if e.get("error") else "")
        lines.append(f"| {e['format']} | {e['variant']} | {files} | {total} | {e.get('graph', '—')} | {e['status']} | {rel} | {note} |")
    lines += ["", "Environment: " + ", ".join(f"{k} {v}" for k, v in env.items() if v) + f"; {platform.platform()}, Python {platform.python_version()}.", ""]
    return "\n".join(lines)


def run(model: str, only: list[str]):
    out = Path("exports") / model
    (out / "logs").mkdir(parents=True, exist_ok=True)
    for exporter in only:
        start = time.perf_counter()
        print(f"[{model}] {exporter} ...", flush=True)
        with open(out / "logs" / f"{exporter}.log", "w") as log:
            code = subprocess.run([sys.executable, "-m", f"tools.export_formats.{exporter}", "--model", model, "--out", str(out)],
                                  stdout=log, stderr=subprocess.STDOUT).returncode
        print(f"[{model}] {exporter} exit {code} in {time.perf_counter() - start:.0f}s (log: {out / 'logs' / f'{exporter}.log'})", flush=True)
    entries = []
    for exporter in EXPORTERS:  # merge every manifest.d file present, also from earlier --only runs
        part = out / "manifest.d" / f"{exporter.split('_')[0]}.json"  # Manifest(args, "<family>") in each exporter
        if part.exists():
            entries += json.loads(part.read_text())
    env = versions()
    (out / "manifest.json").write_text(json.dumps({"format": "tensormorph-export-manifest", "version": 1, "model": model,
                                                   "environment": env, "entries": entries}, indent=1))
    (out / "README.md").write_text(readme(model, entries, env))
    for e in entries:
        rel = f"{e['verify']['max_rel_diff']:.1e}" if e.get("verify") else ""
        print(f"  {e['status']:<9}{e['format']:<15}{e['variant']:<36}{rel}")
    return all(e["status"] in ("ok", "skipped") for e in entries)


parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
parser.add_argument("--model", default="all", choices=[*MODELS, "all"])
parser.add_argument("--only", help="comma-separated exporters (default: all): " + ",".join(EXPORTERS))
args = parser.parse_args()
selected = args.only.split(",") if args.only else EXPORTERS
assert set(selected) <= set(EXPORTERS), f"unknown exporter in {selected}"
results = [run(model, selected) for model in (MODELS if args.model == "all" else [args.model])]
sys.exit(0 if all(results) else 1)
