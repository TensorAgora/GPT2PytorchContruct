    p.add_argument("task")
    p.add_argument("--worker", required=True)
    p.add_argument("--reason", required=True)
    p.add_argument("--evidence")
    p = sub.add_parser("verify-fail", help="async: verification failed; return the task as rework")
    p.add_argument("task")
    p.add_argument("--worker", required=True)
    p.add_argument("--reason", required=True, help="the findings the implementer must fix")
    p.add_argument("--evidence")
    p = sub.add_parser("release", help="async: give a lease back (task id or stage:<module>:<stage>)")
    p.add_argument("item")
    p.add_argument("--worker", required=True)
    p.add_argument("--reason", required=True)
    p.add_argument("--failed", action="store_true", help="count a failed attempt; blocks the module at max_attempts")
    p.add_argument("--force", action="store_true", help="release a lease held by another worker")
    p = sub.add_parser("heartbeat", help="async: extend this worker's leases")
    p.add_argument("--worker", required=True)
