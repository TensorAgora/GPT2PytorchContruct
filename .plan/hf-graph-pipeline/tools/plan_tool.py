def render(plan: Plan) -> list[str]:
    changed = []
    for m in plan.modules:
        plan.refresh_state(m["id"])
    plan.save()
    for m in plan.modules:
        path = plan.module_dir(m) / "TASKS.md"
        if write_if_changed(path, r_module_tasks(plan, m)):
            changed.append(str(path.relative_to(plan.dir)))
    fns = {"STATUS.md": r_plan_status, "REQUIREMENTS.md": r_requirements,
           "EXECUTION_GRAPH.md": r_execution_graph, "QUEUE.md": r_queue}
    for name in plan.plan_files_generated():
        if write_if_changed(plan.dir / name, fns[name](plan)):
            changed.append(name)
    return changed


def r_module_tasks(plan: Plan, m: dict) -> str:
    """One status-only file per module: state, next action, then every task as a checkbox."""
    ms = plan.mstate(m["id"])
    tasks = plan.module_tasks(m)
    closed = sum(1 for t in tasks if plan.task_status(t["id"]) in CLOSED)
    nxt = next_task_in_module(plan, m)
    out = [f"# {m['id']} TASKS: {m['title']}", "", GENERATED, "",
           f"State: **{ms['state']}**. Tasks closed: {closed}/{len(tasks)}. "
           f"Depends on: {', '.join(m.get('depends_on', [])) or 'nothing'}. Blocks: {', '.join(plan.blocks(m['id'])) or 'nothing'}.", ""]
    if ms["state"] == "BLOCKED" and ms.get("blocked"):
        out += [f"BLOCKED: {ms['blocked'].get('reason')}. Unblock when: {ms['blocked'].get('unblock')}", ""]
    waiting = plan.deps_done(m)
    if waiting:
        out += [f"Waiting on: {', '.join(waiting)} (must be DONE before stages that need dependencies).", ""]
    out += ["Next: " + (f"`{nxt['id']}` {nxt['text']}" if nxt else
            (f"close stage {plan.active_stage(m)} with `complete-stage`" if plan.active_stage(m) else "none, module closed.")), "",
            "`[x]` done, `[~]` awaiting verification, `[-]` skipped, `[ ]` open. Boxes change only through the plan tool.", ""]
    stages = m.get("stages") or {}
    for s in plan.lifecycle:
        sid = s["id"]
        st = ms["stages"][sid]["status"]
        out += [f"## Stage {sid} {s['name']} ({st})", ""]
        if sid in plan.skipped_stages(m):
            out += [f"Skipped: {plan.skipped_stages(m)[sid]}", ""]
            continue
        sp = stages.get(sid) or {}
        for ph in sp.get("phases", []):
            out += [f"### {ph['id']} {ph['title']}" + (" (parallel)" if ph.get("parallel") else ""), ""]
            for t in ph.get("tasks", []):
                tst = plan.task_status(t["id"])
                box = {"done": "[x]", "skipped": "[-]", "submitted": "[~]"}.get(tst, "[ ]")
                reqs = f" ({', '.join(t['requirements'])})" if t.get("requirements") else ""
                out.append(f"- {box} `{t['id']}` {t['text']}{reqs}")
                ts = plan.mstate(m["id"])["tasks"].get(t["id"]) or {}
                if tst == "open":
                    out.append(f"      verify: {t['verify']}")
                    if t.get("depends_on"):
                        out.append(f"      after: {', '.join(t['depends_on'])}")
                    if ts.get("rework"):
                        out.append(f"      rework: {ts['rework'][-1].get('findings')}")
                elif tst == "skipped":
                    out.append(f"      skipped: {ts.get('reason', '')}")
            out.append("")
        out += [f"Gate: {sp.get('gate') or s['exit_criteria']}", ""]
    out += ["## Acceptance", ""]
    for a in m.get("acceptance", []):
        box = "[x]" if plan.task_status(a["verified_by"]) == "done" else "[ ]"
        out.append(f"- {box} {a['text']} (`{a['verified_by']}`)")
    out.append("")
    if m.get("blockers"):
        out += ["## Likely blockers", ""] + [f"- {b.get('blocker')}: {b.get('response')}" for b in m["blockers"]] + [""]
    return "\n".join(out)


def r_plan_status(plan: Plan) -> str:
    p = plan.spec["plan"]
    counts: dict[str, int] = {}
    for m in plan.modules:
        st = plan.mstate(m["id"])["state"]
        counts[st] = counts.get(st, 0) + 1
    total_t = len(plan.tasks)
    closed_t = sum(1 for t in plan.tasks if plan.task_status(t) in ("done", "skipped"))
    out = ["# STATUS", "", GENERATED, "", f"Plan: {p['title']} (version {p['version']}).", "",
           f"Tasks closed: {closed_t} of {total_t}. Modules: " + ", ".join(f"{k} {v}" for k, v in counts.items()) + ".", "",
           "## Per module", ""]
    rows = []
    for mid in topo_order(plan):
        m = plan.mod_by_id[mid]
        tasks = plan.module_tasks(m)
        closed = sum(1 for t in tasks if plan.task_status(t["id"]) in ("done", "skipped"))
        rows.append([f"[{mid}]({m['id']}-{m['slug']}/TASKS.md)", m["title"], m["wave"], plan.mstate(mid)["state"],
                     plan.active_stage(m) or "-", f"{closed}/{len(tasks)}", ", ".join(plan.deps_done(m))])
    out += [table(["module", "title", "wave", "state", "active stage", "tasks", "waiting on"], rows), ""]
    out += ["## Next actions", ""]
    nxt = next_actions(plan)
    out += ([f"- {x}" for x in nxt] or ["- Nothing actionable: every module is DONE or BLOCKED."]) + [""]
    blocked = [m for m in plan.modules if plan.mstate(m["id"])["state"] == "BLOCKED"]
    if blocked:
        out += ["## Blocked", ""]
        for m in blocked:
            b = plan.mstate(m["id"]).get("blocked") or {}
            out.append(f"- {m['id']}: {b.get('reason')}; unblock when: {b.get('unblock')}")
        out.append("")
    return "\n".join(out)


def conflict_reason(plan: Plan, a: dict, b: dict) -> str | None:
    """Why modules a and b may not be worked on at the same time, or None if they may."""
    if b["id"] in ancestors(plan, a["id"]):
        return f"{a['id']} needs {b['id']} first (dependency)"
    if a["id"] in ancestors(plan, b["id"]):
        return f"{b['id']} needs {a['id']} first (dependency)"
    if b["id"] in plan.serial_peers(a):
        return "serialize_with (shared resource)"
    def overlap(x: str, y: str) -> bool:
        x, y = x.rstrip("/"), y.rstrip("/")
        return x == y or x.startswith(y + "/") or y.startswith(x + "/")
    shared = sorted({x for x in a.get("write_set", []) for y in b.get("write_set", []) if overlap(x, y)})
    if shared:
        return "shared write set " + ", ".join(f"`{x}`" for x in shared)
    return None


def wave_steps(plan: Plan, wave_id) -> list[list[str]]:
    """Modules of one wave grouped into steps by dependencies inside the wave."""
    mods = [m["id"] for m in plan.modules if m["wave"] == wave_id]
    level: dict[str, int] = {}
    def lv(mid: str) -> int:
        if mid not in level:
            inner = [d for d in plan.mod_by_id[mid].get("depends_on", []) if d in mods]
            level[mid] = 0 if not inner else 1 + max(lv(d) for d in inner)
        return level[mid]
    steps: dict[int, list[str]] = {}
    for mid in mods:
        steps.setdefault(lv(mid), []).append(mid)
    return [steps[k] for k in sorted(steps)]


def parallel_width(plan: Plan, mids: list[str]) -> int:
    chosen: list[dict] = []
    for mid in mids:
        m = plan.mod_by_id[mid]
        if all(conflict_reason(plan, m, c) is None for c in chosen):
            chosen.append(m)
    return len(chosen)


def critical_path(plan: Plan) -> tuple[list[str], int]:
    best: dict[str, tuple[int, list[str]]] = {}
    for mid in topo_order(plan):
        m = plan.mod_by_id[mid]
        w = COMPLEXITY_WEIGHT.get(m.get("complexity"), 2)
        prev = max((best[d] for d in m.get("depends_on", []) if d in best), default=(0, []), key=lambda x: x[0])
        best[mid] = (prev[0] + w, prev[1] + [mid])
    if not best:
        return [], 0
    total, path = max(best.values(), key=lambda x: x[0])
    return path, total


def r_execution_graph(plan: Plan) -> str:
    waves = plan.spec.get("waves", [])
    out = ["# EXECUTION_GRAPH (what runs in parallel, what runs in sequence)", "", GENERATED, "",
           "Derived from `depends_on`, `serialize_with` and `write_set` of modules, and from `parallel` phases, task "
           "`depends_on` and verification mode of tasks. Two modules may be worked on at the same time only when "
           "neither depends on the other (directly or transitively), they are not `serialize_with` each other, and their "
           "write sets do not overlap.", "", "## Wave dependency graph", "",
           "Solid arrow: module dependency (the target waits until the source is DONE). Dotted link: never at the same "
           "time (`serialize_with`).", "", "```mermaid", "flowchart LR"]
    for w in waves:
        out.append(f'  subgraph W{w["id"]}["Wave {w["id"]}: {md_escape(w.get("focus", "")).replace(chr(34), "")}"]')
        out.append("    direction TB")
        for m in plan.modules:
            if m["wave"] == w["id"]:
                out.append(f'    m{m["id"]}["{m["id"]} {m["slug"]}<br/>{m["complexity"]} · {len(plan.module_tasks(m))} tasks"]')
