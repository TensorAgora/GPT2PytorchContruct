def subst(text: str, values: dict) -> str:
    return re.sub(r"\{\{([A-Z_]+)\}\}", lambda mo: str(values.get(mo.group(1), mo.group(0))), text)


def scaffold(plan: Plan, tpl: Path) -> list[str]:
    created = []
    p = plan.spec["plan"]
    rel_plan = str(plan.dir.relative_to(plan.root)) if plan.dir.is_relative_to(plan.root) else str(plan.dir)
    pv = {"PLAN_TITLE": p["title"], "PLAN_SLUG": p["slug"], "PLAN_VERSION": p["version"],
          "MASTER_DOCUMENT": p["master_document"], "OBJECTIVE": p["objective"], "PLAN_DIR": rel_plan,
          "MODULE_COUNT": len(plan.modules), "TASK_COUNT": len(plan.tasks),
          "REQUIREMENT_COUNT": len(plan.req_by_id), "WAVE_COUNT": len(plan.spec.get("waves", [])),
          "STAGE_LIST": ", ".join(f"{s['id']} {s['name']}" for s in plan.lifecycle), "TODAY": now()[:10],
          "SESSION_PREFIX": plan.execution["session_prefix"], "MAX_WORKERS": plan.execution["max_workers"],
          "ASYNC_STAGES": ", ".join(s["id"] for s in plan.lifecycle
                                    if plan.task_mode({"_stage": s["id"]}) == "async") or "none"}
    for f in plan.plan_files_authored():
        src, dst = tpl / "plan" / f, plan.dir / f
        if src.exists() and not dst.exists():
            dst.write_text(subst(src.read_text(encoding="utf-8"), pv), encoding="utf-8")
            created.append(f)
    for m in plan.modules:
        mv = dict(pv)
        mv.update({"ID": m["id"], "SLUG": m["slug"], "TITLE": m["title"], "GOAL": m["goal"], "KIND": m["kind"],
                   "WAVE": m["wave"], "COMPLEXITY": m["complexity"], "DIR": f"{m['id']}-{m['slug']}",
                   "DEPENDS": ", ".join(m.get("depends_on", [])) or "none",
                   "BLOCKS": ", ".join(plan.blocks(m["id"])) or "none",
                   "REQUIREMENTS": ", ".join(m.get("requirements", [])),
                   "MASTER_SECTIONS": ", ".join(m.get("master_sections", [])),
                   "DELIVERABLES": "\n".join(f"- {d}" for d in m.get("deliverables", [])) or "- <!-- FILL: deliverables -->",
                   "WRITE_SET": "\n".join(f"- `{w}`" for w in m.get("write_set", [])) or "- <!-- FILL: files and directories this module may change -->",
                   "NON_GOALS": "\n".join(f"- {n}" for n in m.get("non_goals", [])) or "- <!-- FILL: explicit non-goals -->",
                   "REQUIREMENT_ROWS": table(["id", "requirement", "master source"],
                                             [[r, plan.req_by_id[r]["text"], plan.req_by_id[r]["source"]] for r in m.get("requirements", [])]),
                   "ACCEPTANCE_ROWS": table(["criterion", "verified by"],
                                            [[a["text"], a["verified_by"]] for a in m.get("acceptance", [])])})
        d = plan.module_dir(m)
        d.mkdir(parents=True, exist_ok=True)
        for f in MODULE_FILES_AUTHORED:
            src, dst = tpl / "module" / f, d / f
            if src.exists() and not dst.exists():
                dst.write_text(subst(src.read_text(encoding="utf-8"), mv), encoding="utf-8")
                created.append(f"{d.name}/{f}")
    return created


