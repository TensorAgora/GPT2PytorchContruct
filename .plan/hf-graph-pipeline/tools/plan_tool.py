# the plan model

class Plan:
    def __init__(self, plan_dir: Path):
        self.dir = plan_dir.resolve()
        self.spec_path = self.dir / "tools" / "plan-spec.json"
        self.state_path = self.dir / "tools" / "plan-state.json"
        if not self.spec_path.exists():
            raise PlanError(f"no spec at {self.spec_path}")
        self.spec = load_json(self.spec_path)
        self.state = load_json(self.state_path) if self.state_path.exists() else {"modules": {}}
        self.root = repo_root(self.dir)
        self.lifecycle = self.spec.get("lifecycle") or DEFAULT_LIFECYCLE
        self.stage_ids = [s["id"] for s in self.lifecycle]
        self.stage_by_id = {s["id"]: s for s in self.lifecycle}
        self.modules = self.spec.get("modules", [])
        self.mod_by_id = {m["id"]: m for m in self.modules}
        self.req_by_id = {r["id"]: r for r in self.spec.get("requirements", [])}
        self.async_enabled = self.spec.get("execution") is not None
        self.execution = {**DEFAULT_EXECUTION, **(self.spec.get("execution") or {})}
        self.execution.setdefault("session_prefix", "cc-" + str(self.spec.get("plan", {}).get("slug", "plan"))[:24])
        self._assign_task_ids()
        self._ensure_state()

    # -- structure -----------------------------------------------------------
    def _assign_task_ids(self) -> None:
        self.tasks: dict[str, dict] = {}
        self.phases: dict[str, dict] = {}
        for m in self.modules:
            for sid, stage in (m.get("stages") or {}).items():
                for pi, phase in enumerate(stage.get("phases", []), 1):
                    phase.setdefault("id", f"{m['id']}.{sid}.P{pi}")
                    phase["_module"], phase["_stage"] = m["id"], sid
                    self.phases[phase["id"]] = phase
                    for ti, task in enumerate(phase.get("tasks", []), 1):
                        task.setdefault("id", f"{phase['id']}.T{ti}")
                        task["_module"], task["_stage"], task["_phase"] = m["id"], sid, phase["id"]
                        if task["id"] in self.tasks:
                            raise PlanError(f"duplicate task id {task['id']}")
                        self.tasks[task["id"]] = task

    def module_dir(self, m: dict) -> Path:
        return self.dir / f"{m['id']}-{m['slug']}"

    def harness(self, item: str, what: str, instead: str = "") -> None:
        """Append one row to HARNESS.md (its table is the last block of the file); identical rows are kept once."""
        path = self.dir / "HARNESS.md"
        if not path.exists():
            return
        cells = [md_escape(x) or "-" for x in (item, what, instead)]
        text = path.read_text(encoding="utf-8")
        if f"| {cells[0]} | {cells[1]} |" in text:
            return
        row = f"| {now()[:10]} | {' | '.join(cells)} |"
        path.write_text(text.rstrip("\n") + "\n" + row + "\n", encoding="utf-8")

    def blocks(self, mid: str) -> list[str]:
        return [m["id"] for m in self.modules if mid in m.get("depends_on", [])]

    def skipped_stages(self, m: dict) -> dict:
        return m.get("skip_stages", {}) or {}

    def module_tasks(self, m: dict, sid: str | None = None) -> list[dict]:
        return [t for t in self.tasks.values() if t["_module"] == m["id"] and (sid is None or t["_stage"] == sid)]

    # -- state ---------------------------------------------------------------
    def _ensure_state(self) -> None:
        if self.async_enabled:
            self.state.setdefault("leases", {})
            self.state.setdefault("attempts", {})
            self.state.setdefault("workers", {})
            self.state.setdefault("events", [])
        mods = self.state.setdefault("modules", {})
        for m in self.modules:
            ms = mods.setdefault(m["id"], {})
            ms.setdefault("state", "NOT_STARTED")
            ms.setdefault("stages", {})
            ms.setdefault("tasks", {})
            ms.setdefault("transitions", [])
            ms.setdefault("blocked", None)
            for sid in self.stage_ids:
                if sid in self.skipped_stages(m):
                    ms["stages"][sid] = {"status": "skipped", "reason": self.skipped_stages(m)[sid]}
                else:
                    ms["stages"].setdefault(sid, {"status": "pending"})

    def mstate(self, mid: str) -> dict:
        return self.state["modules"][mid]

    def task_status(self, tid: str) -> str:
        t = self.tasks[tid]
        return self.mstate(t["_module"])["tasks"].get(tid, {}).get("status", "open")

    def stage_status(self, mid: str, sid: str) -> str:
        return self.mstate(mid)["stages"][sid]["status"]

    def is_done(self, mid: str) -> bool:
        return self.mstate(mid)["state"] == "DONE"

    def deps_done(self, m: dict) -> list[str]:
        return [d for d in m.get("depends_on", []) if not self.is_done(d)]

    def active_stage(self, m: dict) -> str | None:
        for sid in self.stage_ids:
            if self.stage_status(m["id"], sid) == "pending":
                return sid
        return None

    def derived_state(self, m: dict) -> str:
        st = "NOT_STARTED"
        for sid in self.stage_ids:
            s = self.stage_status(m["id"], sid)
            if s in ("done", "skipped"):
                st = self.stage_by_id[sid]["exit_state"]
            else:
                break
        if st == "NOT_STARTED" and any(self.task_status(t["id"]) != "open" for t in self.module_tasks(m)):
            st = "IN_PROGRESS"
        return st

    def refresh_state(self, mid: str) -> None:
        ms = self.mstate(mid)
        if ms["state"] == "BLOCKED":
            return
        new = self.derived_state(self.mod_by_id[mid])
        if new != ms["state"]:
            ms["transitions"].append({"from": ms["state"], "to": new, "at": now(), "reason": "derived from stage progress"})
            ms["state"] = new

    def save(self) -> None:
        dump_json(self.state_path, self.state)

    def plan_files_authored(self) -> list[str]:
        return PLAN_FILES_AUTHORED + (PLAN_FILES_AUTHORED_ASYNC if self.async_enabled else [])

    def plan_files_generated(self) -> list[str]:
        return PLAN_FILES_GENERATED + (["QUEUE.md"] if self.async_enabled else [])

    # -- asynchronous execution ---------------------------------------------
    def task_mode(self, t: dict) -> str:
        """`async`: a different worker verifies after `submit`; `inline`: the implementer verifies."""
        if not self.async_enabled:
            return "inline"
        if t.get("verify_mode") in ("async", "inline"):
            return t["verify_mode"]
        stages = self.execution.get("async_stages")
        if stages is not None:
            return "async" if t["_stage"] in stages else "inline"
        return "async" if self.stage_by_id[t["_stage"]].get("async_verify") else "inline"

    def is_parallel_phase(self, pid: str) -> bool:
        return bool(self.phases.get(pid, {}).get("parallel"))

    def task_deps_open(self, t: dict) -> list[str]:
        """Explicit task prerequisites (`depends_on`) not yet done or skipped."""
        return [d for d in t.get("depends_on", []) if d in self.tasks and self.task_status(d) not in CLOSED]

    def serial_peers(self, m: dict) -> set[str]:
        """Modules that must never hold work at the same time as this one (`serialize_with`, both directions)."""
        peers = set(m.get("serialize_with", []))
        peers |= {x["id"] for x in self.modules if m["id"] in x.get("serialize_with", [])}
        peers.discard(m["id"])
        return peers

    def leases(self) -> dict:
        return self.state.setdefault("leases", {})

    def lease_of(self, key: str) -> dict | None:
        return self.leases().get(key)

    def module_impl_lease(self, mid: str) -> dict | None:
        ls = self.module_impl_leases(mid)
        return ls[0] if ls else None

    def module_impl_leases(self, mid: str) -> list[dict]:
        return [le for le in self.leases().values() if le["module"] == mid and le["role"] in ("implement", "close-stage")]

    def serial_peer_busy(self, m: dict) -> str | None:
        busy = {le["module"] for le in self.leases().values()}
        return next(iter(sorted(self.serial_peers(m) & busy)), None)

    def event(self, text: str) -> None:
        ev = self.state.setdefault("events", [])
        ev.append(f"{now()} {text}")
        del ev[:-200]

    def expire_leases(self) -> None:
        t = _dt.datetime.now(_dt.timezone.utc)
        for key, le in list(self.leases().items()):
            if parse_time(le["expires"]) < t:
                self.leases().pop(key)
                record_failure(self, key, le["module"], f"lease held by {le['worker']} expired")

    def new_lease(self, key: str, worker: str, role: str, mid: str, sid: str, task: str | None) -> dict:
        t = _dt.datetime.now(_dt.timezone.utc).replace(microsecond=0)
        le = {"key": key, "worker": worker, "role": role, "module": mid, "stage": sid, "task": task,
              "at": t.isoformat(),
              "expires": (t + _dt.timedelta(minutes=float(self.execution["lease_minutes"]))).isoformat()}
        self.leases()[key] = le
        self.event(f"{worker} claimed {role} {key}")
        return le

    def claimable_stages(self, m: dict) -> list[str]:
        """The active stage, plus the next one when speculation is on and the active stage has no open task."""
        active = self.active_stage(m)
        if not active:
            return []
        out = [active]
        if self.async_enabled and self.execution.get("speculative_next_stage"):
            if not any(self.task_status(t["id"]) == "open" for t in self.module_tasks(m, active)):
                for sid in self.stage_ids[self.stage_ids.index(active) + 1:]:
                    if self.stage_status(m["id"], sid) == "pending":
                        out.append(sid)
                        break
        ready = []
        for s in out:
            if self.stage_by_id[s].get("needs_dependencies") and self.deps_done(m):
                break
            ready.append(s)
        return ready

    @staticmethod
    def ref(args) -> str:
        """Optional short reference recorded with a status (commit, file, command); never checked on disk."""
        return (getattr(args, "evidence", None) or "").strip()


