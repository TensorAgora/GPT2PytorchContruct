def default_plan_dir() -> Path | None:
    here = Path(__file__).resolve().parent
    if here.name == "tools" and (here / "plan-spec.json").exists():
        return here.parent
    return None


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--plan-dir", help="plan directory (default: the plan this tool lives in)")
    common = argparse.ArgumentParser(add_help=False)
    common.add_argument("--plan-dir", default=argparse.SUPPRESS, help="plan directory")
    sub = ap.add_subparsers(dest="cmd", required=True)
    _add = sub.add_parser
    sub.add_parser = lambda *a, **k: _add(*a, parents=[common], **k)

    p = sub.add_parser("init", help="create a plan tree from a spec")
    p.add_argument("--spec", required=True)
    p.add_argument("--templates", help="template directory (default: the skill's templates/)")
    p.add_argument("--force", action="store_true", help="replace an existing plan-spec.json (state is kept)")
    sub.add_parser("render", help="regenerate every generated file")
    p = sub.add_parser("validate", help="check spec, state, files and links")
    p.add_argument("--draft", action="store_true", help="report FILL markers as warnings, not errors")
    p = sub.add_parser("next", help="the next legal tasks, in dependency order")
    p.add_argument("--limit", type=int, default=10)
    p = sub.add_parser("show")
    p.add_argument("module", nargs="?")
    for name in ("complete-task", "skip-task", "reopen-task"):
        p = sub.add_parser(name)
        p.add_argument("task")
        p.add_argument("--reason", required=True, help="the verified result, or why it is skipped or reopened")
        if name == "complete-task":
            p.add_argument("--evidence", help="optional short reference (commit, file, command)")
        if name != "reopen-task":
            p.add_argument("--worker", help="async mode: the worker holding the lease")
    p = sub.add_parser("complete-stage")
    p.add_argument("module")
    p.add_argument("stage")
    p.add_argument("--reason", required=True)
    p.add_argument("--evidence")
    p.add_argument("--worker", help="async mode: the worker holding the close-stage lease")
    p = sub.add_parser("claim", help="async: lease the next work item for a worker")
    p.add_argument("--worker", required=True)
    p.add_argument("--role", choices=["any", "implement", "verify"], default="any")
    p.add_argument("--json", action="store_true")
    p = sub.add_parser("submit", help="async: implementation done; queue the task for independent verification")
    p.add_argument("task")
    p.add_argument("--worker", required=True)
    p.add_argument("--reason", required=True, help="what was implemented and which checks the implementer ran")
