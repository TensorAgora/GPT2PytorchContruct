# state commands

def _task(plan: Plan, tid: str) -> dict:
    if tid not in plan.tasks:
        raise PlanError(f"unknown task {tid}")
    return plan.tasks[tid]


def _guard_module(plan: Plan, m: dict, sid: str, task_level: bool = False, leased: bool = False) -> None:
    ms = plan.mstate(m["id"])
    if ms["state"] == "BLOCKED":
        raise PlanError(f"{m['id']} is BLOCKED ({(ms.get('blocked') or {}).get('reason')}); unblock it first")
    if ms["state"] == "DONE":
        raise PlanError(f"{m['id']} is DONE; reopen a stage first")
    active = plan.active_stage(m)
    reachable = active is not None and plan.stage_ids.index(sid) <= plan.stage_ids.index(active)
    if task_level and not reachable and (sid in plan.claimable_stages(m) or (leased and sid == next_pending_stage(plan, m))):
        reachable = True  # speculative work on the next stage while the active one awaits verification
    if not reachable:
        raise PlanError(f"{m['id']}: stage {sid} is not reachable; the active stage is {active}")
    if plan.stage_status(m["id"], sid) != "pending":
        raise PlanError(f"{m['id']} stage {sid} is already {plan.stage_status(m['id'], sid)}; reopen it first")


def next_pending_stage(plan: Plan, m: dict) -> str | None:
    active = plan.active_stage(m)
    if not active:
        return None
    return next((s for s in plan.stage_ids[plan.stage_ids.index(active) + 1:]
                 if plan.stage_status(m["id"], s) == "pending"), None)


def _check_task_stage(plan: Plan, m: dict, t: dict, worker: str | None = None) -> None:
    """The task's stage must be active, or (speculation) the next one: claimable now, or leased when it was."""
    le = plan.lease_of(t["id"]) if plan.async_enabled else None
    leased = bool(worker and le and le["worker"] == worker and le["role"] == "implement")
    _guard_module(plan, m, t["_stage"], task_level=True, leased=leased)
    if not (leased and t["_stage"] in (plan.active_stage(m), next_pending_stage(plan, m))) \
            and t["_stage"] != plan.active_stage(m) and t["_stage"] not in plan.claimable_stages(m):
        raise PlanError(f"{t['id']} belongs to stage {t['_stage']}, but the active stage is {plan.active_stage(m)}")
    if plan.task_deps_open(t):
        raise PlanError(f"{t['id']} depends on tasks not yet done: {', '.join(plan.task_deps_open(t))}")


def _check_lease(plan: Plan, key: str, worker: str | None, role: str | None = None) -> None:
    """A worker may only record work it holds the lease for; a human (no --worker) may not touch a leased item."""
    if not plan.async_enabled:
        return
    le = plan.lease_of(key)
    if worker is None:
        if le:
            raise PlanError(f"{key} is leased by {le['worker']} ({le['role']}); pass --worker or release it first")
        return
    if not le or le["worker"] != worker:
        raise PlanError(f"{worker} does not hold the lease for {key}" + (f" ({le['worker']} does)" if le else ""))
    if role and le["role"] != role:
        raise PlanError(f"{key} is leased for {le['role']}, not {role}")


def _drop_lease(plan: Plan, key: str) -> None:
    if plan.async_enabled:
        plan.leases().pop(key, None)


def cmd_complete_task(plan: Plan, args) -> int:
    t = _task(plan, args.task)
    m = plan.mod_by_id[t["_module"]]
    _check_task_stage(plan, m, t, args.worker)
    if plan.task_mode(t) == "async":
        raise PlanError(f"{t['id']} is verified asynchronously: `submit` it, then a different worker runs "
                        "`verify-pass` or `verify-fail`")
    if plan.task_status(t["id"]) != "open":
        raise PlanError(f"{t['id']} is already {plan.task_status(t['id'])}")
    _check_lease(plan, t["id"], args.worker, "implement")
    ev = plan.ref(args)
    if plan.stage_by_id[t["_stage"]].get("needs_dependencies") and plan.deps_done(m):
        print(f"warning: stage {t['_stage']} cannot complete until {', '.join(plan.deps_done(m))} is DONE", file=sys.stderr)
    entry = {"status": "done", "reason": args.reason, "evidence": ev, "at": now()}
    if args.worker:
        entry["implemented_by"] = entry["verified_by"] = args.worker
    plan.mstate(m["id"])["tasks"][t["id"]] = entry
    _drop_lease(plan, t["id"])
    return _finish(plan, m, f"task {t['id']} done")


def cmd_skip_task(plan: Plan, args) -> int:
    t = _task(plan, args.task)
    m = plan.mod_by_id[t["_module"]]
    _guard_module(plan, m, t["_stage"])
    if plan.spec.get("acceptance_tasks_unskippable", True) and any(a["verified_by"] == t["id"] for a in m.get("acceptance", [])):
        raise PlanError(f"{t['id']} verifies an acceptance criterion and cannot be skipped; change the spec with a DECISIONS entry instead")
    _check_lease(plan, t["id"], getattr(args, "worker", None))
    plan.mstate(m["id"])["tasks"][t["id"]] = {"status": "skipped", "reason": args.reason, "at": now()}
    _drop_lease(plan, t["id"])
    return _finish(plan, m, f"task {t['id']} skipped")


def cmd_reopen_task(plan: Plan, args) -> int:
    t = _task(plan, args.task)
    m = plan.mod_by_id[t["_module"]]
    if plan.stage_status(m["id"], t["_stage"]) == "done":
        raise PlanError(f"stage {t['_stage']} of {m['id']} is done; reopen-stage first")
    ms = plan.mstate(m["id"])
    old = ms["tasks"].pop(t["id"], None)
    _drop_lease(plan, t["id"])
    ms["transitions"].append({"from": ms["state"], "to": ms["state"], "at": now(),
                              "reason": f"task {t['id']} reopened ({(old or {}).get('status', 'open')}): {args.reason}"})
    return _finish(plan, m, f"task {t['id']} reopened")


def cmd_complete_stage(plan: Plan, args) -> int:
    m = plan.mod_by_id.get(args.module) or _raise(f"unknown module {args.module}")
    sid = args.stage
    if sid not in plan.stage_by_id:
        raise PlanError(f"unknown stage {sid}")
    _guard_module(plan, m, sid)
    if sid != plan.active_stage(m):
        raise PlanError(f"stages complete in order; the active stage of {m['id']} is {plan.active_stage(m)}")
    open_t = [t["id"] for t in plan.module_tasks(m, sid) if plan.task_status(t["id"]) not in CLOSED]
    if open_t:
        raise PlanError(f"unclosed tasks in {m['id']} stage {sid} (open or awaiting verification): {', '.join(open_t)}")
    if plan.stage_by_id[sid].get("needs_dependencies") and plan.deps_done(m):
        raise PlanError(f"stage {sid} needs dependencies DONE; waiting on {', '.join(plan.deps_done(m))}")
    if plan.stage_by_id[sid]["exit_state"] == "DONE":
        unverified = [a["text"] for a in m.get("acceptance", []) if plan.task_status(a["verified_by"]) != "done"]
        if unverified:
            raise PlanError("acceptance criteria not verified: " + "; ".join(unverified))
    skey = f"stage:{m['id']}:{sid}"
    _check_lease(plan, skey, args.worker, "close-stage")
    ev = plan.ref(args)
    ms = plan.mstate(m["id"])
    ms["stages"][sid] = {"status": "done", "reason": args.reason, "evidence": ev, "at": now()}
    _drop_lease(plan, skey)
    new = plan.derived_state(m)
    ms["transitions"].append({"from": ms["state"], "to": new, "at": now(),
                              "reason": f"Stage {sid} {plan.stage_by_id[sid]['name']} complete: {args.reason}", "evidence": ev})
    ms["state"] = new
    return _finish(plan, m, f"{m['id']} stage {sid} done; state {new}")


def cmd_reopen_stage(plan: Plan, args) -> int:
    m = plan.mod_by_id.get(args.module) or _raise(f"unknown module {args.module}")
    ms = plan.mstate(m["id"])
    if ms["stages"].get(args.stage, {}).get("status") != "done":
        raise PlanError(f"{m['id']} stage {args.stage} is not done")
    idx = plan.stage_ids.index(args.stage)
    for sid in plan.stage_ids[idx:]:
        if ms["stages"][sid]["status"] == "done":
            ms["stages"][sid] = {"status": "pending"}
    new = plan.derived_state(m)
    ms["transitions"].append({"from": ms["state"], "to": new, "at": now(), "reason": f"stage {args.stage} reopened: {args.reason}"})
    ms["state"] = new
    return _finish(plan, m, f"{m['id']} stage {args.stage} reopened; state {new}")


def cmd_block(plan: Plan, args) -> int:
    m = plan.mod_by_id.get(args.module) or _raise(f"unknown module {args.module}")
    ms = plan.mstate(m["id"])
    if ms["state"] in ("BLOCKED", "DONE"):
        raise PlanError(f"{m['id']} is already {ms['state']}")
    ev = plan.ref(args)
    ms["blocked"] = {"reason": args.reason, "unblock": args.unblock, "at": now(), "left": ms["state"], "evidence": ev}
    plan.harness(m["id"], f"blocked: {args.reason}", f"unblock when: {args.unblock}")
    if plan.async_enabled:
        for key, le in list(plan.leases().items()):
            if le["module"] == m["id"]:
                plan.leases().pop(key)
                plan.event(f"lease {key} of {le['worker']} dropped: {m['id']} BLOCKED")
    ms["transitions"].append({"from": ms["state"], "to": "BLOCKED", "at": now(), "reason": args.reason, "evidence": ev})
    ms["state"] = "BLOCKED"
    return _finish(plan, m, f"{m['id']} BLOCKED")


def cmd_unblock(plan: Plan, args) -> int:
    m = plan.mod_by_id.get(args.module) or _raise(f"unknown module {args.module}")
    ms = plan.mstate(m["id"])
    if ms["state"] != "BLOCKED":
        raise PlanError(f"{m['id']} is not BLOCKED")
    ev = plan.ref(args)
    new = plan.derived_state(m)
    if plan.async_enabled:
        for key in list(plan.state.get("attempts", {})):
            if (key in plan.tasks and plan.tasks[key]["_module"] == m["id"]) or key.startswith(f"stage:{m['id']}:"):
                plan.state["attempts"].pop(key)
    ms["transitions"].append({"from": "BLOCKED", "to": new, "at": now(), "reason": args.reason, "evidence": ev})
    ms["state"], ms["blocked"] = new, None
    return _finish(plan, m, f"{m['id']} unblocked; state {new}")


def _raise(msg: str):
    raise PlanError(msg)


def _finish(plan: Plan, m: dict, msg: str) -> int:
    plan.save()
    render(plan)
    print(msg)
    if plan.mstate(m["id"])["state"] == "BLOCKED":
        return 0
    nxt = next_task_in_module(plan, m)
    sid = plan.active_stage(m)
    if nxt:
        print(f"next in {m['id']}: {nxt['id']} {nxt['text']}")
    elif sid and any(plan.task_status(t["id"]) == "submitted" for t in plan.module_tasks(m, sid)):
        print(f"stage {sid} of {m['id']} is waiting for verification of submitted tasks")
    elif sid:
        print(f"all tasks of stage {sid} closed: run complete-stage {m['id']} {sid}")
    return 0


