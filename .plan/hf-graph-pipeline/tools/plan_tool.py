def cmd_validate(plan: Plan, args) -> int:
    serrs = validate_spec(plan)
    sterrs = validate_state(plan) if not serrs else []
    ferrs, warns = validate_files(plan, args.draft)
    accepted = {r for m in plan.modules for a in m.get("acceptance", []) for r in a.get("requirements", [])}
    warns += [f"must-requirement {r} appears in no acceptance criterion" for r, v in plan.req_by_id.items()
              if v.get("priority", "must") == "must" and r not in accepted]
    warns += write_set_overlaps(plan) + parallel_warnings(plan)
    if plan.async_enabled:
        warns += [f"module {m['id']} has no write_set; parallel workers cannot respect its file ownership"
                  for m in plan.modules if not m.get("write_set")]
    errs = serrs + sterrs + ferrs
    for e in errs:
        print(f"ERROR {e}")
    for w in warns:
        print(f"WARN  {w}")
    print("PASS" if not errs else f"FAIL: {len(errs)} error(s)")
    return 0 if not errs else 1


def cmd_next(plan: Plan, args) -> int:
    acts = next_actions(plan)
    if not acts:
        print("nothing actionable: every module is DONE, BLOCKED, or waiting on a dependency")
        return 0
    for a in acts[: args.limit]:
        print(a)
    return 0


def cmd_show(plan: Plan, args) -> int:
    if not args.module:
        for mid in topo_order(plan):
            m = plan.mod_by_id[mid]
            tasks = plan.module_tasks(m)
            closed = sum(1 for t in tasks if plan.task_status(t["id"]) in ("done", "skipped"))
            print(f"{mid:6} {plan.mstate(mid)['state']:14} stage {plan.active_stage(m) or '-':2} tasks {closed}/{len(tasks)}  {m['title']}")
        return 0
    m = plan.mod_by_id.get(args.module) or _raise(f"unknown module {args.module}")
    print(json.dumps(plan.mstate(m["id"]), indent=2))
    return 0


