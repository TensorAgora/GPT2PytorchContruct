def validate_spec(plan: Plan) -> list[str]:
    errs: list[str] = []
    spec = plan.spec
    p = spec.get("plan", {})
    for key in ("slug", "title", "version", "master_document", "objective"):
        if not p.get(key):
            errs.append(f"plan.{key} is missing")
    if p.get("slug") and not SLUG_RE.match(p["slug"]):
        errs.append(f"plan.slug {p['slug']!r} must be lowercase kebab-case")

    seen_stage = set()
    exit_states = []
    for s in plan.lifecycle:
        for key in ("id", "name", "exit_state", "purpose", "exit_criteria"):
            if not s.get(key):
                errs.append(f"lifecycle stage {s.get('id', '?')} lacks {key}")
        if s.get("id") in seen_stage:
            errs.append(f"duplicate lifecycle stage {s['id']}")
        seen_stage.add(s.get("id"))
        exit_states.append(s.get("exit_state"))
    if plan.lifecycle and plan.lifecycle[-1].get("exit_state") != "DONE":
        errs.append("the last lifecycle stage must have exit_state DONE")
    if len(set(exit_states)) != len(exit_states):
        errs.append("lifecycle exit states must be unique")
    for bad in ("NOT_STARTED", "IN_PROGRESS", "BLOCKED"):
        if bad in exit_states:
            errs.append(f"lifecycle exit_state {bad} is reserved")

    reqs = spec.get("requirements", [])
    if not reqs:
        errs.append("requirements register is empty")
    rid_seen = set()
    for r in reqs:
        if not r.get("id") or not r.get("text") or not r.get("source"):
            errs.append(f"requirement {r.get('id', '?')} needs id, text and source (master section)")
        if r.get("id") in rid_seen:
            errs.append(f"duplicate requirement {r['id']}")
        rid_seen.add(r.get("id"))

    wave_ids = [w.get("id") for w in spec.get("waves", [])]
    if not wave_ids:
        errs.append("no waves defined")

    mids, slugs = set(), set()
    for m in plan.modules:
        mid = m.get("id", "?")
        for key in ("id", "slug", "title", "goal", "wave", "complexity", "kind", "master_sections"):
            if m.get(key) in (None, "", []):
                errs.append(f"module {mid} lacks {key}")
        if not ID_RE.match(str(mid)):
            errs.append(f"module id {mid!r} has illegal characters")
        if mid in mids:
            errs.append(f"duplicate module id {mid}")
        if m.get("slug") in slugs:
            errs.append(f"duplicate module slug {m.get('slug')}")
        mids.add(mid)
        slugs.add(m.get("slug"))
        if m.get("slug") and not SLUG_RE.match(m["slug"]):
            errs.append(f"module {mid} slug must be lowercase kebab-case")
        if m.get("wave") not in wave_ids:
            errs.append(f"module {mid} wave {m.get('wave')} is not a defined wave")
        if m.get("complexity") not in ("S", "M", "L", "XL"):
            errs.append(f"module {mid} complexity must be S, M, L or XL")
        for r in m.get("requirements", []):
            if r not in plan.req_by_id:
                errs.append(f"module {mid} names unknown requirement {r}")
        if not m.get("requirements"):
            errs.append(f"module {mid} owns no requirement")
        stages = m.get("stages") or {}
        for sid in stages:
            if sid not in plan.stage_by_id:
                errs.append(f"module {mid} has unknown stage {sid}")
        for sid, reason in plan.skipped_stages(m).items():
            if sid not in plan.stage_by_id:
                errs.append(f"module {mid} skips unknown stage {sid}")
            if not reason:
                errs.append(f"module {mid} skips stage {sid} without a reason")
            if sid in stages and any(ph.get("tasks") for ph in stages[sid].get("phases", [])):
                errs.append(f"module {mid} skips stage {sid} but lists tasks for it")
        if plan.stage_ids and plan.stage_ids[-1] in plan.skipped_stages(m):
            errs.append(f"module {mid} may not skip the final stage")
        for sid in plan.stage_ids:
            if sid in plan.skipped_stages(m):
                continue
            if not plan.module_tasks(m, sid):
                errs.append(f"module {mid} stage {sid} has no task (add tasks or skip the stage with a reason)")
            for ph in (stages.get(sid) or {}).get("phases", []):
                if not ph.get("title"):
                    errs.append(f"phase {ph.get('id')} has no title")
        for t in plan.module_tasks(m):
            if not t.get("text"):
                errs.append(f"task {t['id']} has no text")
            if not t.get("verify"):
                errs.append(f"task {t['id']} has no verify (how completion is checked)")
            for r in t.get("requirements", []):
                if r not in plan.req_by_id:
                    errs.append(f"task {t['id']} names unknown requirement {r}")
                elif r not in m.get("requirements", []):
                    errs.append(f"task {t['id']} covers {r}, which module {mid} does not own")
        if not m.get("acceptance"):
            errs.append(f"module {mid} has no acceptance criteria")
        for i, a in enumerate(m.get("acceptance", []), 1):
            if not a.get("text"):
                errs.append(f"module {mid} acceptance {i} has no text")
            vb = a.get("verified_by")
            if not vb or vb not in plan.tasks or plan.tasks[vb]["_module"] != mid:
                errs.append(f"module {mid} acceptance {i} verified_by {vb!r} is not a task of this module")

    for m in plan.modules:
        for d in m.get("depends_on", []):
            if d == m["id"]:
                errs.append(f"module {m['id']} depends on itself")
            elif d not in plan.mod_by_id:
                errs.append(f"module {m['id']} depends on unknown module {d}")
            elif wave_ids and m.get("wave") in wave_ids and plan.mod_by_id[d].get("wave") in wave_ids:
                if wave_ids.index(plan.mod_by_id[d]["wave"]) > wave_ids.index(m["wave"]):
                    errs.append(f"module {m['id']} (wave {m['wave']}) depends on {d} in a later wave")

    cycle = find_cycle(plan)
    if cycle:
        errs.append("dependency cycle: " + " -> ".join(cycle))

    for t in plan.tasks.values():
        if t.get("verify_mode") not in (None, "async", "inline"):
            errs.append(f"task {t['id']} verify_mode must be 'async' or 'inline'")
    errs += validate_ordering(plan)
    ex = spec.get("execution")
    if ex is not None:
        if not isinstance(ex, dict):
            errs.append("execution must be an object")
        else:
            cmd = ex.get("agent_command", DEFAULT_EXECUTION["agent_command"])
            if not (isinstance(cmd, list) and cmd and all(isinstance(c, str) for c in cmd)):
                errs.append("execution.agent_command must be a non-empty list of strings (argv)")
            elif not any("{prompt}" in c or "{prompt_file}" in c for c in cmd):
                errs.append("execution.agent_command must contain {prompt} or {prompt_file}")
            if not isinstance(ex.get("allowed_tools", []), list):
                errs.append("execution.allowed_tools must be a list")
            for key in ("max_workers", "lease_minutes", "poll_seconds", "idle_exit_polls", "max_attempts",
                        "agent_timeout_minutes"):
                if key in ex and not (isinstance(ex[key], (int, float)) and ex[key] > 0):
                    errs.append(f"execution.{key} must be a positive number")
            for s in ex.get("async_stages") or []:
                if s not in plan.stage_by_id:
                    errs.append(f"execution.async_stages names unknown stage {s}")
            if int(ex.get("max_workers", DEFAULT_EXECUTION["max_workers"])) < 2 and not ex.get("allow_self_verify"):
                errs.append("execution.max_workers must be at least 2 (an implementer never verifies its own task) "
                            "unless allow_self_verify is true")
            if ex.get("session_prefix") and not SLUG_RE.match(ex["session_prefix"]):
                errs.append("execution.session_prefix must be lowercase kebab-case")

    covered = {r for t in plan.tasks.values() for r in t.get("requirements", [])}
    for rid in plan.req_by_id:
        if rid not in covered:
            errs.append(f"requirement {rid} is covered by no task")
    owned = {r for m in plan.modules for r in m.get("requirements", [])}
    for rid in plan.req_by_id:
        if rid not in owned:
            errs.append(f"requirement {rid} is owned by no module")
    return errs


def find_cycle(plan: Plan) -> list[str]:
    color: dict[str, int] = {}
    stack: list[str] = []

    def visit(n: str) -> list[str]:
        color[n] = 1
        stack.append(n)
        for d in plan.mod_by_id.get(n, {}).get("depends_on", []):
            if d not in plan.mod_by_id:
                continue
            if color.get(d) == 1:
                return stack[stack.index(d):] + [d]
            if not color.get(d):
                c = visit(d)
                if c:
                    return c
        stack.pop()
        color[n] = 2
        return []

    for m in plan.modules:
        if not color.get(m["id"]):
            c = visit(m["id"])
            if c:
                return c
    return []


def task_order(plan: Plan, m: dict) -> list[str]:
    return [t["id"] for sid in plan.stage_ids for t in plan.module_tasks(m, sid)]


def validate_ordering(plan: Plan) -> list[str]:
    """Task-level `depends_on`, parallel phases and `serialize_with` must describe a schedule that can finish."""
    errs = []
    for m in plan.modules:
        order = task_order(plan, m)
        anc = ancestors(plan, m["id"])
        for t in plan.module_tasks(m):
            deps = t.get("depends_on", [])
            if not isinstance(deps, list):
                errs.append(f"task {t['id']} depends_on must be a list of task ids")
                continue
            for d in deps:
                if d == t["id"]:
                    errs.append(f"task {t['id']} depends on itself")
                elif d not in plan.tasks:
                    errs.append(f"task {t['id']} depends on unknown task {d}")
                elif plan.tasks[d]["_module"] == m["id"]:
                    if order.index(d) > order.index(t["id"]):
                        errs.append(f"task {t['id']} depends on {d}, which comes later in the same module (deadlock)")
                elif plan.tasks[d]["_module"] not in anc:
                    errs.append(f"task {t['id']} depends on {d} of module {plan.tasks[d]['_module']}, which is not "
                                f"among {m['id']}'s module dependencies; add it to depends_on")
            if not isinstance(t.get("write_set", []), list):
                errs.append(f"task {t['id']} write_set must be a list")
        for key in ("serialize_with", "write_set"):
            if not isinstance(m.get(key, []), list):
                errs.append(f"module {m['id']} {key} must be a list")
        for x in m.get("serialize_with", []) if isinstance(m.get("serialize_with", []), list) else []:
            if x == m["id"] or x not in plan.mod_by_id:
                errs.append(f"module {m['id']} serialize_with names {x!r}, which is not another module")
    for pid, ph in plan.phases.items():
        if "parallel" in ph and not isinstance(ph["parallel"], bool):
            errs.append(f"phase {pid} parallel must be true or false")
    return errs


def parallel_warnings(plan: Plan) -> list[str]:
    def overlap(a: str, b: str) -> bool:
        a, b = a.rstrip("/"), b.rstrip("/")
        return a == b or a.startswith(b + "/") or b.startswith(a + "/")

    out = []
    for pid, ph in plan.phases.items():
        if not ph.get("parallel"):
            continue
        tasks = ph.get("tasks", [])
        missing = [t["id"] for t in tasks if not t.get("write_set")]
        if missing:
            out.append(f"parallel phase {pid}: tasks without write_set ({', '.join(missing)}) cannot be checked for conflicts")
        for i, a in enumerate(tasks):
            for b in tasks[i + 1:]:
                shared = sorted({x for x in a.get("write_set", []) for y in b.get("write_set", []) if overlap(x, y)})
                if shared:
                    out.append(f"parallel phase {pid}: {a['id']} and {b['id']} both write {', '.join(shared)}; "
                               "make the phase sequential or split the files")
    return out


def ancestors(plan: Plan, mid: str) -> set[str]:
    seen: set[str] = set()
    stack = list(plan.mod_by_id.get(mid, {}).get("depends_on", []))
    while stack:
        d = stack.pop()
        if d in seen or d not in plan.mod_by_id:
            continue
        seen.add(d)
        stack.extend(plan.mod_by_id[d].get("depends_on", []))
    return seen


def write_set_overlaps(plan: Plan) -> list[str]:
    """Modules that may run at the same time (no dependency path between them) must not share files."""
    def overlap(a: str, b: str) -> bool:
        a, b = a.rstrip("/"), b.rstrip("/")
        return a == b or a.startswith(b + "/") or b.startswith(a + "/")

    out = []
    anc = {m["id"]: ancestors(plan, m["id"]) for m in plan.modules}
    for i, m in enumerate(plan.modules):
        for n in plan.modules[i + 1:]:
            if n["id"] in anc[m["id"]] or m["id"] in anc[n["id"]] or n["id"] in plan.serial_peers(m):
                continue
            shared = sorted({a for a in m.get("write_set", []) for b in n.get("write_set", []) if overlap(a, b)})
            if shared:
                out.append(f"modules {m['id']} and {n['id']} can run concurrently but share write_set {', '.join(shared)}; "
                           "add a dependency or serialize_with, or split the files")
    return out


def topo_order(plan: Plan) -> list[str]:
    wave_ids = [w["id"] for w in plan.spec.get("waves", [])]
    order, done = [], set()
    pending = sorted(plan.modules, key=lambda m: (wave_ids.index(m["wave"]) if m["wave"] in wave_ids else 99, m["id"]))
    while pending:
        progressed = False
        for m in list(pending):
            if all(d in done or d not in plan.mod_by_id for d in m.get("depends_on", [])):
                order.append(m["id"])
                done.add(m["id"])
                pending.remove(m)
                progressed = True
                break
        if not progressed:
            order.extend(m["id"] for m in pending)
            break
    return order


def validate_state(plan: Plan) -> list[str]:
    errs = []
    known_mods = set(plan.mod_by_id)
    for mid, ms in plan.state.get("modules", {}).items():
        if mid not in known_mods:
            errs.append(f"state has module {mid}, which the spec no longer defines")
            continue
        m = plan.mod_by_id[mid]
        for tid, ts in ms.get("tasks", {}).items():
            if tid not in plan.tasks:
                errs.append(f"state records task {tid}, which the spec no longer defines (task ids are keys: append, never reorder)")
                continue
            if ts.get("status") == "done" and plan.async_enabled and plan.task_mode(plan.tasks[tid]) == "async" \
                    and ts.get("verified_by") and ts.get("verified_by") == ts.get("implemented_by") \
                    and not plan.execution.get("allow_self_verify"):
                errs.append(f"task {tid} was verified by its own implementer {ts['verified_by']}")
            if ts.get("status") in ("done", "skipped") and not ts.get("reason"):
                errs.append(f"task {tid} is {ts['status']} without a reason")
        for sid in plan.stage_ids:
            st = ms["stages"].get(sid, {})
            if st.get("status") == "done":
                open_tasks = [t["id"] for t in plan.module_tasks(m, sid) if plan.task_status(t["id"]) not in CLOSED]
                if open_tasks:
                    errs.append(f"{mid} stage {sid} is done with unclosed tasks: {', '.join(open_tasks)}")
                prior = plan.stage_ids[:plan.stage_ids.index(sid)]
                for p in prior:
                    if ms["stages"].get(p, {}).get("status") == "pending":
                        errs.append(f"{mid} stage {sid} is done before stage {p}")
        if ms.get("state") == "BLOCKED":
            if not (ms.get("blocked") or {}).get("unblock"):
                errs.append(f"{mid} is BLOCKED without an unblocking condition")
        elif ms.get("state") != plan.derived_state(m):
            errs.append(f"{mid} state {ms.get('state')} disagrees with its stages ({plan.derived_state(m)}); run render")
        if ms.get("state") == "DONE":
            for a in m.get("acceptance", []):
                if plan.task_status(a["verified_by"]) != "done":
                    errs.append(f"{mid} is DONE but acceptance '{a['text']}' is unverified")
    return errs


def validate_files(plan: Plan, draft: bool) -> tuple[list[str], list[str]]:
    errs, warns = [], []
    for f in plan.plan_files_authored() + plan.plan_files_generated():
        if not (plan.dir / f).exists():
            errs.append(f"plan file missing: {f}")
    for m in plan.modules:
        d = plan.module_dir(m)
        for f in MODULE_FILES_AUTHORED + MODULE_FILES_GENERATED:
            if not (d / f).exists():
                errs.append(f"{d.name}/{f} is missing")
    authored = [plan.dir / f for f in plan.plan_files_authored()] + \
               [plan.module_dir(m) / f for m in plan.modules for f in MODULE_FILES_AUTHORED]
    for p in authored:
        if p.exists() and FILL_RE.search(p.read_text(encoding="utf-8")):
            n = len(FILL_RE.findall(p.read_text(encoding="utf-8")))
            msg = f"{p.relative_to(plan.dir)} still has {n} FILL marker(s)"
            (warns if draft else errs).append(msg)
    for p in sorted(plan.dir.rglob("*.md")):
        if "tools" in p.relative_to(plan.dir).parts:
            continue
        text = p.read_text(encoding="utf-8")
        for target in LINK_RE.findall(text):
            if target.startswith("<!--"):
                continue
            target = target[1:-1] if target.startswith("<") else target
            if re.match(r"^[a-z]+:", target) or target.startswith("#"):
                continue
            path = unquote(target.split("#", 1)[0])
            if path and not (p.parent / path).exists():
                errs.append(f"{p.relative_to(plan.dir)} links to a missing file: {target}")
    return errs, warns


