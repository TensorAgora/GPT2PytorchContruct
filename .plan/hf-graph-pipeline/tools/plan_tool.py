def next_task_in_module(plan: Plan, m: dict) -> dict | None:
    sid = plan.active_stage(m)
    if not sid:
        return None
    for t in plan.module_tasks(m, sid):
        if plan.task_status(t["id"]) == "open":
            return t
    return None


def next_actions(plan: Plan) -> list[str]:
    out = []
    for mid in topo_order(plan):
        m = plan.mod_by_id[mid]
        ms = plan.mstate(mid)
        if ms["state"] in ("DONE", "BLOCKED"):
            continue
        sid = plan.active_stage(m)
        if not sid:
            continue
        stage = plan.stage_by_id[sid]
        waiting = plan.deps_done(m)
        if stage.get("needs_dependencies") and waiting:
            continue
        t = next_task_in_module(plan, m)
        if t:
            out.append(f"{mid} stage {sid}: `{t['id']}` {t['text']}")
        elif any(plan.task_status(x["id"]) == "submitted" for x in plan.module_tasks(m, sid)):
            waiting_v = [x["id"] for x in plan.module_tasks(m, sid) if plan.task_status(x["id"]) == "submitted"]
            out.append(f"{mid} stage {sid}: awaiting verification of {', '.join(waiting_v)}")
        else:
            out.append(f"{mid} stage {sid}: all tasks closed; run `complete-stage {mid} {sid}`")
    return out


