def _require_async(plan: Plan) -> None:
    if not plan.async_enabled:
        raise PlanError("asynchronous execution is off: add an \"execution\" block to tools/plan-spec.json and render")


def _touch_worker(plan: Plan, worker: str) -> None:
    plan.state.setdefault("workers", {})[worker] = {"last_seen": now()}


def _task_item(plan: Plan, t: dict, role: str, le: dict) -> dict:
    m = plan.mod_by_id[t["_module"]]
    ts = plan.mstate(m["id"])["tasks"].get(t["id"], {})
    rel = lambda p: str(p.relative_to(plan.root)) if p.is_relative_to(plan.root) else str(p)
    return {"role": role, "key": le["key"], "task": t["id"], "module": m["id"], "stage": t["_stage"],
            "phase": t["_phase"], "text": t["text"], "verify": t["verify"], "verify_mode": plan.task_mode(t),
            "requirements": t.get("requirements", []), "module_dir": rel(plan.module_dir(m)),
            "phase_mode": "parallel" if plan.is_parallel_phase(t["_phase"]) else "sequential",
            "task_write_set": t.get("write_set", []), "depends_on": t.get("depends_on", []),
            "write_set": m.get("write_set", []), "submitted": ts if ts.get("status") == "submitted" else None,
            "rework": ts.get("rework", []), "attempt": plan.state.get("attempts", {}).get(le["key"], 0) + 1,
            "lease_expires": le["expires"]}


def _stage_item(plan: Plan, m: dict, sid: str, le: dict) -> dict:
    s = plan.stage_by_id[sid]
    rel = lambda p: str(p.relative_to(plan.root)) if p.is_relative_to(plan.root) else str(p)
    gate = ((m.get("stages") or {}).get(sid) or {}).get("gate") or s["exit_criteria"]
    return {"role": "close-stage", "key": le["key"], "module": m["id"], "stage": sid, "text":
            f"Close stage {sid} {s['name']} of {m['id']}", "verify": gate, "module_dir": rel(plan.module_dir(m)),
            "write_set": m.get("write_set", []), "attempt": plan.state.get("attempts", {}).get(le["key"], 0) + 1,
            "lease_expires": le["expires"]}


def _stuck(plan: Plan, key: str) -> bool:
    return plan.state.get("attempts", {}).get(key, 0) >= int(plan.execution["max_attempts"])


def record_failure(plan: Plan, key: str, mid: str, reason: str) -> str:
    """Count a failed unattended attempt; at max_attempts the module is BLOCKED for a human."""
    n = plan.state.setdefault("attempts", {})[key] = plan.state["attempts"].get(key, 0) + 1
    msg = f"{key}: {reason} (failed attempt {n} of {plan.execution['max_attempts']})"
    ms = plan.mstate(mid)
    if n >= int(plan.execution["max_attempts"]) and ms["state"] not in ("BLOCKED", "DONE"):
        ms["blocked"] = {"reason": f"{key} failed {n} unattended attempts; last: {reason}",
                         "unblock": "a human reads HARNESS.md and the agent logs in tools/_runs/, fixes the "
                                    "cause, then runs unblock", "at": now(), "left": ms["state"], "evidence": ""}
        ms["transitions"].append({"from": ms["state"], "to": "BLOCKED", "at": now(), "reason": ms["blocked"]["reason"]})
        ms["state"] = "BLOCKED"
        for k, other in list(plan.leases().items()):
            if other["module"] == mid:
                plan.leases().pop(k)
        msg += f"; {mid} BLOCKED for a human"
    if "expired" not in reason:  # ponytail: lease expiry carries no lesson; only agent-given reasons go to HARNESS
        plan.harness(key, reason)
    plan.event(msg)
    return msg


def module_candidates(plan: Plan, m: dict) -> list[dict]:
    """Tasks of module m that a worker may start implementing now, in plan order.

    Sequential phase: only its first open task (the next in line). Parallel phase
    (`"parallel": true`): every open task. A later phase starts only when the earlier
    one has no open task (its tasks may still await verification: that is the pipeline).
    A task with unmet `depends_on` is not startable, and in a sequential phase it holds
    the line. One implementer per module, except inside one parallel phase.
    """
    if plan.mstate(m["id"])["state"] in ("DONE", "BLOCKED") or plan.serial_peer_busy(m):
        return []
    impl = plan.module_impl_leases(m["id"])
    only_phase = None
    if impl:
        phases = {plan.tasks[le["task"]]["_phase"] for le in impl if le.get("task")}
        if any(le["role"] == "close-stage" for le in impl) or len(phases) != 1 \
                or not plan.is_parallel_phase(next(iter(phases))):
            return []
        only_phase = next(iter(phases))
    for sid in plan.claimable_stages(m):
        open_tasks = [t for t in plan.module_tasks(m, sid) if plan.task_status(t["id"]) == "open"]
        if not open_tasks:
            continue  # stage fully submitted or closed: speculative work may start on the next stage
        pid = open_tasks[0]["_phase"]
        if only_phase and pid != only_phase:
            return []
        in_phase = [t for t in open_tasks if t["_phase"] == pid]
        if not plan.is_parallel_phase(pid):
            in_phase = in_phase[:1]
        return [t for t in in_phase if not plan.lease_of(t["id"]) and not _stuck(plan, t["id"])
                and not plan.task_deps_open(t)]
    return []


def find_work(plan: Plan, worker: str, role: str) -> tuple[str, str, str, str | None] | None:
    """(role, key, module, task) of the best unleased item for this worker, or None."""
    live = [m for m in (plan.mod_by_id[x] for x in topo_order(plan)) if plan.mstate(m["id"])["state"] not in ("DONE", "BLOCKED")]
    if role in ("any", "verify"):
        subs = []
        for m in live:
            if plan.serial_peer_busy(m):
                continue
            for t in plan.module_tasks(m):
                ts = plan.mstate(m["id"])["tasks"].get(t["id"], {})
                if ts.get("status") != "submitted" or plan.lease_of(t["id"]) or _stuck(plan, t["id"]):
                    continue
                if ts.get("submitted_by") == worker and not plan.execution.get("allow_self_verify"):
                    continue
                subs.append((ts.get("at", ""), m["id"], t["id"]))
        if subs:
            _, mid, tid = sorted(subs)[0]
            return "verify", tid, mid, tid
    if role == "verify":
        return None
    for m in live:  # close a stage whose tasks are all verified
        if plan.module_impl_lease(m["id"]) or plan.serial_peer_busy(m):
            continue
        sid = plan.active_stage(m)
        key = f"stage:{m['id']}:{sid}"
        if sid and not plan.lease_of(key) and not _stuck(plan, key) \
                and all(plan.task_status(t["id"]) in CLOSED for t in plan.module_tasks(m, sid)) \
                and not (plan.stage_by_id[sid].get("needs_dependencies") and plan.deps_done(m)):
            return "close-stage", key, m["id"], None
    cands = [(m, module_candidates(plan, m)) for m in live]
    for want_rework in (True, False):  # rework first, then new work
        for m, ts in cands:
            for t in ts:
                if not want_rework or plan.mstate(m["id"])["tasks"].get(t["id"], {}).get("rework"):
                    return ("rework" if want_rework else "implement"), t["id"], m["id"], t["id"]
    return None


def cmd_claim(plan: Plan, args) -> int:
    _require_async(plan)
    plan.expire_leases()
    _touch_worker(plan, args.worker)
    held = [le for le in plan.leases().values() if le["worker"] == args.worker]
    if held:  # idempotent: a restarted worker gets its own lease back
        le = held[0]
        item = _stage_item(plan, plan.mod_by_id[le["module"]], le["stage"], le) if le["role"] == "close-stage" \
            else _task_item(plan, plan.tasks[le["task"]], le["role"], le)
        item["resumed"] = True
    else:
        found = find_work(plan, args.worker, args.role)
        if not found:
            done = all(plan.is_done(m["id"]) for m in plan.modules)
            item = {"role": "idle", "plan_done": done, "outstanding_leases": len(plan.leases()),
                    "reason": "plan complete" if done else "nothing claimable now: work is leased, awaiting "
                              "verification by another worker, blocked, or waiting on dependencies"}
        else:
            role, key, mid, tid = found
            m = plan.mod_by_id[mid]
            if role == "close-stage":
                le = plan.new_lease(key, args.worker, role, mid, plan.active_stage(m), None)
                item = _stage_item(plan, m, le["stage"], le)
            else:
                t = plan.tasks[tid]
                le = plan.new_lease(key, args.worker, "verify" if role == "verify" else "implement", mid, t["_stage"], tid)
                item = _task_item(plan, t, role, le)
    plan.save()
    render(plan)
    if args.json:
        print(json.dumps(item, indent=2, ensure_ascii=False))
    elif item["role"] == "idle":
        print(f"idle: {item['reason']}")
    else:
        print(f"{item['role']} {item.get('task') or item['key']}: {item['text']}\n  verify: {item['verify']}")
    return 0


def cmd_submit(plan: Plan, args) -> int:
    _require_async(plan)
    t = _task(plan, args.task)
    m = plan.mod_by_id[t["_module"]]
    _check_task_stage(plan, m, t, args.worker)
    if plan.task_mode(t) != "async":
        raise PlanError(f"{t['id']} is verified inline: run its verify check and use complete-task")
    if plan.task_status(t["id"]) != "open":
        raise PlanError(f"{t['id']} is {plan.task_status(t['id'])}, not open")
    _check_lease(plan, t["id"], args.worker, "implement")
    ev = plan.ref(args)
    tasks = plan.mstate(m["id"])["tasks"]
    prev = tasks.get(t["id"], {})
    tasks[t["id"]] = {"status": "submitted", "reason": args.reason, "evidence": ev, "submitted_by": args.worker,
                      "at": now(), "rework": prev.get("rework", [])}
    _drop_lease(plan, t["id"])
    plan.state.get("attempts", {}).pop(t["id"], None)
    plan.event(f"{args.worker} submitted {t['id']} for verification")
    return _finish(plan, m, f"task {t['id']} submitted; queued for verification by another worker")


def cmd_verify_pass(plan: Plan, args) -> int:
    _require_async(plan)
    t = _task(plan, args.task)
    m = plan.mod_by_id[t["_module"]]
    ts = plan.mstate(m["id"])["tasks"].get(t["id"], {})
    if ts.get("status") != "submitted":
        raise PlanError(f"{t['id']} is not awaiting verification")
    _check_lease(plan, t["id"], args.worker, "verify")
    if ts.get("submitted_by") == args.worker and not plan.execution.get("allow_self_verify"):
        raise PlanError(f"{args.worker} implemented {t['id']} and may not verify it")
    ev = plan.ref(args)
    evidence = ",".join(x for x in dict.fromkeys(ts.get("evidence", "").split(",") + ev.split(",")) if x)
    plan.mstate(m["id"])["tasks"][t["id"]] = {
        "status": "done", "reason": args.reason, "evidence": evidence, "at": now(),
        "implemented_by": ts.get("submitted_by"), "implementation": ts.get("reason"), "verified_by": args.worker,
        "rework": ts.get("rework", [])}
    _drop_lease(plan, t["id"])
    plan.state.get("attempts", {}).pop(t["id"], None)
    plan.event(f"{args.worker} verified {t['id']}")
    return _finish(plan, m, f"task {t['id']} verified and done")


def cmd_verify_fail(plan: Plan, args) -> int:
    _require_async(plan)
    t = _task(plan, args.task)
    m = plan.mod_by_id[t["_module"]]
    ts = plan.mstate(m["id"])["tasks"].get(t["id"], {})
    if ts.get("status") != "submitted":
        raise PlanError(f"{t['id']} is not awaiting verification")
    _check_lease(plan, t["id"], args.worker, "verify")
    ev = plan.ref(args)
    rework = ts.get("rework", []) + [{"at": now(), "by": args.worker, "findings": args.reason, "evidence": ev,
                                      "implementation": ts.get("reason"), "implemented_by": ts.get("submitted_by")}]
    plan.mstate(m["id"])["tasks"][t["id"]] = {"status": "open", "rework": rework}
    plan.harness(t["id"], f"failed verification: {args.reason}")
    _drop_lease(plan, t["id"])
    plan.event(f"{args.worker} rejected {t['id']}: rework queued")
    return _finish(plan, m, f"task {t['id']} failed verification; queued for rework (attempt {len(rework) + 1})")


def cmd_release(plan: Plan, args) -> int:
    _require_async(plan)
    key = args.item
    le = plan.lease_of(key)
    if not le:
        print(f"{key} is not leased")
        return 0
    if le["worker"] != args.worker and not args.force:
        raise PlanError(f"{key} is leased by {le['worker']}; pass --force to take it away")
    plan.leases().pop(key)
    m = plan.mod_by_id[le["module"]]
    if args.failed:
        msg = record_failure(plan, key, m["id"], f"released by {args.worker}: {args.reason}")
    else:
        msg = f"{key} released by {args.worker}: {args.reason}"
        plan.event(msg)
    return _finish(plan, m, msg)


def cmd_heartbeat(plan: Plan, args) -> int:
    _require_async(plan)
    _touch_worker(plan, args.worker)
    t = _dt.datetime.now(_dt.timezone.utc).replace(microsecond=0)
    n = 0
    for le in plan.leases().values():
        if le["worker"] == args.worker:
            le["expires"] = (t + _dt.timedelta(minutes=float(plan.execution["lease_minutes"]))).isoformat()
            n += 1
    plan.save()
    print(f"{args.worker}: {n} lease(s) extended")
    return 0


def queue_snapshot(plan: Plan) -> dict:
    snap = {"async": plan.async_enabled, "leases": list(plan.state.get("leases", {}).values()),
            "awaiting_verification": [], "rework": [], "ready": [], "stuck": [],
            "plan_done": all(plan.is_done(m["id"]) for m in plan.modules),
            "blocked": [m["id"] for m in plan.modules if plan.mstate(m["id"])["state"] == "BLOCKED"],
            "workers": plan.state.get("workers", {}), "events": plan.state.get("events", [])[-15:]}
    if not plan.async_enabled:
        return snap
    for mid in topo_order(plan):
        m = plan.mod_by_id[mid]
        if plan.mstate(mid)["state"] in ("DONE", "BLOCKED"):
            continue
        for t in plan.module_tasks(m):
            ts = plan.mstate(mid)["tasks"].get(t["id"], {})
            if _stuck(plan, t["id"]):
                snap["stuck"].append(t["id"])
            if ts.get("status") == "submitted" and not plan.lease_of(t["id"]):
                snap["awaiting_verification"].append({"task": t["id"], "submitted_by": ts.get("submitted_by")})
            elif ts.get("status") == "open" and ts.get("rework") and not plan.lease_of(t["id"]):
                snap["rework"].append(t["id"])
        snap["ready"] += [t["id"] for t in module_candidates(plan, m)]
        sid = plan.active_stage(m)
        if sid and not plan.module_impl_lease(mid) and not plan.serial_peer_busy(m) \
                and not plan.lease_of(f"stage:{mid}:{sid}") \
                and all(plan.task_status(t["id"]) in CLOSED for t in plan.module_tasks(m, sid)) \
                and not (plan.stage_by_id[sid].get("needs_dependencies") and plan.deps_done(m)):
            snap["ready"].append(f"stage:{mid}:{sid}")
    snap["demand"] = len(snap["leases"]) + len(snap["awaiting_verification"]) + len(snap["ready"])
    return snap


def cmd_queue(plan: Plan, args) -> int:
    plan.expire_leases() if plan.async_enabled else None
    snap = queue_snapshot(plan)
    if plan.async_enabled:
        plan.save()
    if args.json:
        print(json.dumps(snap, indent=2, ensure_ascii=False))
        return 0
    print(r_queue(plan, snap))
    return 0


def r_queue(plan: Plan, snap: dict | None = None) -> str:
    out = ["# QUEUE (asynchronous work)", "", GENERATED, ""]
    if not plan.async_enabled:
        return "\n".join(out + ["Asynchronous execution is off for this plan (the spec has no `execution` block). "
                                "Work sequentially with CONTINUE.md.", ""])
    snap = snap or queue_snapshot(plan)
    out += ["Workers pull items with `plan_tool.py claim`; see [ORCHESTRATION.md](ORCHESTRATION.md). Priority: "
            "verification, stage closing, rework, new implementation. One implementer per module at a time; "
            "a task is never verified by the worker that implemented it.", "",
            f"Plan done: {'yes' if snap['plan_done'] else 'no'}. Blocked modules: {', '.join(snap['blocked']) or 'none'}.", "",
            "## Leases", "",
            table(["item", "role", "worker", "since", "expires"],
                  [[le["key"], le["role"], le["worker"], le["at"], le["expires"]] for le in snap["leases"]])
            if snap["leases"] else "None.", "",
            "## Awaiting verification", "",
            ", ".join(f"`{x['task']}` (by {x['submitted_by']})" for x in snap["awaiting_verification"]) or "None.", "",
            "## Rework requested", "", ", ".join(f"`{x}`" for x in snap["rework"]) or "None.", "",
            "## Ready to implement", "", ", ".join(f"`{x}`" for x in snap["ready"]) or "None.", ""]
    if snap["stuck"]:
        out += ["## Stuck (max attempts reached)", "", ", ".join(f"`{x}`" for x in snap["stuck"]), ""]
    return "\n".join(out)


