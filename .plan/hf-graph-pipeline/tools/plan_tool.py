#!/usr/bin/env python3
"""Scaffold, render, validate and advance a module-based implementation plan.

Standard library only. One file, copied into every plan it creates as
<plan>/tools/plan_tool.py, so a plan never depends on the skill that made it.

Sources of truth (never edit the generated Markdown by hand):

  tools/plan-spec.json   structure: requirements, waves, lifecycle, modules,
                         stages, phases, tasks, acceptance criteria
  tools/plan-state.json  progress: task, stage and module states (status only)

Commands:

  init      --spec FILE --plan-dir DIR   create the plan tree from a spec
  render                                 regenerate every generated file
  validate  [--draft]                    check spec, state, files and links
  next                                   the next legal module and task
  show      [MODULE]                     state of the plan or of one module
  complete-task  TASK --reason R            R is a one-line status, not a report
  skip-task      TASK --reason R
  reopen-task    TASK --reason R
  complete-stage MODULE STAGE --reason R
  reopen-stage   MODULE STAGE --reason R
  block          MODULE --reason R --unblock CONDITION   (also appends to HARNESS.md)
  unblock        MODULE --reason R
  harness        ITEM --what W [--instead I]  record what failed or must not be done

--evidence REF is optional on every recording command: a short reference
(commit, file, command) kept with the status. Nothing checks it on disk.

Asynchronous execution (only when the spec has an "execution" block; see
tools/orchestrate.py for the tmux worker pool that drives these):

  claim        --worker W [--role any|implement|verify] [--json]
               atomically lease the next work item: verification first,
               then stage closing, rework, then new implementation
  submit       TASK --worker W --reason R
               implementation finished; queue the task for verification
  verify-pass  TASK --worker W --reason R
  verify-fail  TASK --worker W --reason FINDINGS   (also appends to HARNESS.md)
  release      ITEM --worker W --reason R [--failed] [--force]
  heartbeat    --worker W
  queue        [--json]

Every command holds an exclusive lock on tools/.plan-state.lock, so many
workers can share one plan without losing updates.
"""

